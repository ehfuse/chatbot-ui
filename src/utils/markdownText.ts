/**
 * 마크다운 원문에서 기호를 걷어내 한 줄 미리보기 텍스트로 만든다.
 * 이전 대화 목록처럼 서식을 렌더할 수 없는 자리에서 "**굵게**" 같은 기호가 그대로 보이지 않게 한다.
 */

/** 마크다운 기호를 제거해 사람이 읽는 평문 한 줄로 만든다. */
export function toPlainPreview(markdown: string): string {
    return (
        markdown
            // 코드블록 ```...``` 은 통째로 안내문으로 바꾼다(미리보기에 코드를 늘어놓을 자리가 없다).
            .replace(/```[\s\S]*?```/g, " (코드) ")
            // 인라인 코드·강조 기호는 감싼 기호만 벗기고 안의 글자는 남긴다.
            .replace(/`([^`]+)`/g, "$1")
            .replace(/\*\*([^*]+)\*\*/g, "$1")
            .replace(/__([^_]+)__/g, "$1")
            .replace(/(^|[^*])\*([^*\n]+)\*/g, "$1$2")
            // 링크·이미지는 보이는 글자만 남긴다.
            .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
            .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
            // 줄머리 기호(제목 #, 인용 >, 목록 -·*·1.)를 없앤다.
            .replace(/^[ \t]*#{1,6}[ \t]+/gm, "")
            .replace(/^[ \t]*>[ \t]?/gm, "")
            .replace(/^[ \t]*[-*+][ \t]+/gm, "")
            .replace(/^[ \t]*\d+\.[ \t]+/gm, "")
            // 표 구분선(|---|---|)은 통째로 버린다.
            .replace(/^[ \t]*\|?[ \t]*:?-{2,}:?[ \t]*(\|[ \t]*:?-{2,}:?[ \t]*)*\|?[ \t]*$/gm, "")
            // 남은 줄바꿈·연속 공백을 한 칸으로 접는다(한 줄 말줄임이 제대로 걸리게).
            .replace(/\s+/g, " ")
            .trim()
    );
}
